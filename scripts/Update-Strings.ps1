<#
.SYNOPSIS
    Regenerates src/PresenceSync.Core/Resources/Strings.cs from Strings.resx.

.DESCRIPTION
    Strings.resx (English, neutral) is the source of truth for resource keys; Strings.de.resx holds the German
    translations. Run this script after adding or removing a key in Strings.resx. The unit test
    LocalizationTests checks that every key exists in both files and has the same placeholders.
#>
$ErrorActionPreference = 'Stop'
$dir = Join-Path $PSScriptRoot '..\src\PresenceSync.Core\Resources'
[xml] $resx = Get-Content (Join-Path $dir 'Strings.resx') -Raw -Encoding utf8

$properties = foreach ($data in $resx.root.data) {
    $name = $data.name
    $value = [System.Security.SecurityElement]::Escape(($data.value -split "`n")[0])
    @"
    /// <summary>$value</summary>
    public static string $name => Get(nameof($name));

"@
}

$code = @"
// <auto-generated>Generated by scripts/Update-Strings.ps1 from Strings.resx. Do not edit by hand.</auto-generated>
namespace PresenceSync.Core.Resources;

public static partial class Strings
{
$($properties -join '')}
"@

Set-Content (Join-Path $dir 'Strings.cs') $code.TrimEnd() -Encoding utf8
Write-Output "Strings.cs: $($resx.root.data.Count) keys"
